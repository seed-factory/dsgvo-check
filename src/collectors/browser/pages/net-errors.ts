/** `ERR_<name>` when `code` is one of Chromium's net errors, else null. */
export function chromiumNetError(code: string): string | null {
  return code.startsWith('ERR_') && CHROMIUM_NET_ERRORS.has(code.slice(4)) ? code : null;
}
